#!/usr/bin/env python3
"""Regenerates Sources/HeadphoneLimiter/DatabaseData.swift.

Usage: Tools/make-database.py <checkout of github.com/temirowski/headphone-amp-database>

Data: The Phone Path (thephonepath.com), CC BY 4.0.
"""
import csv, math, sys
from pathlib import Path

root = Path(sys.argv[1]) / "data"
out = Path(__file__).resolve().parent.parent / "Sources/HeadphoneLimiter/DatabaseData.swift"

# Bases where the maker stated the reference, so the dB/mW figure is unambiguous.
SOLID = {"published-per-mW", "converted-from-per-volt", "converted-from-stated-voltage"}
# Models missing from the dataset: (name, ohms, dB/mW). Retailer listings whose dB/mW and dB/V agree.
EXTRA = [("FiiO Snowsky Nature", 24, 101), ("FiiO Snowsky Wind", 32, 101), ("FiiO Snowsky Wind Pro", 16, 100)]

def clean(text):
    return " ".join(text.replace("\t", " ").split())

headphones = {}
for row in csv.DictReader(open(root / "headphones.csv", encoding="utf-8-sig")):
    basis = row["basis"]
    if row["type"] == "electrostatic" or basis not in SOLID | {"unit-not-stated-by-maker"}:
        continue
    try:
        ohms, per_mw = float(row["impedance_ohm"]), float(row["sensitivity_db_mw"])
    except ValueError:
        continue
    if ohms <= 0:
        continue
    headphones[clean(f"{row['brand']} {row['model']}")] = (ohms, per_mw, int(basis in SOLID))
for name, ohms, per_mw in EXTRA:
    headphones.setdefault(name, (ohms, per_mw, 1))

sources = {}
for row in csv.DictReader(open(root / "sources.csv", encoding="utf-8-sig")):
    volts = []
    for load in (32, 150, 300, 600):
        power, basis = row[f"power_mw_{load}_ohm"], row[f"basis_{load}_ohm"]
        try:
            ok = basis != "unverified" and float(power) > 0
        except ValueError:
            ok = False
        volts.append(f"{math.sqrt(float(power) * load / 1000):.3f}" if ok else "")
    if any(volts):
        sources[clean(row["name"])] = volts

def fmt(x):
    return f"{x:g}"

lines = [
    "// Generated by Tools/make-database.py. Do not edit by hand.",
    "// Data: The Phone Path (thephonepath.com), CC BY 4.0.",
    "",
    "enum DatabaseData {",
    "    /// name, impedance in ohms, sensitivity in dB SPL/mW, 1 when the maker stated the unit.",
    '    static let headphones = #"""',
    *[f"{n}\t{fmt(o)}\t{fmt(s)}\t{v}" for n, (o, s, v) in sorted(headphones.items(), key=lambda i: i[0].lower())],
    '"""#',
    "",
    "    /// name, then full-scale volts RMS into 32, 150, 300 and 600 ohms (blank when unknown).",
    '    static let sources = #"""',
    *[f"{n}\t" + "\t".join(v) for n, v in sorted(sources.items(), key=lambda i: i[0].lower())],
    '"""#',
    "}",
    "",
]
out.write_text("\n".join(lines), encoding="utf-8")
print(f"{len(headphones)} headphones ({sum(v for _, _, v in headphones.values())} with stated unit), {len(sources)} sources -> {out}")
